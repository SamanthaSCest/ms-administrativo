-- Vínculo do paciente com convênio (RF06, HU04). O plano fica com outro grupo: o vínculo é direto com o convênio.
-- Desvincular é inativar (ativo = false): o histórico fica para o faturamento.
-- "Só um vínculo ativo por paciente e convênio" (RN05) é checado no serviço: o H2 dos testes não tem índice parcial.
CREATE TABLE pacientes_convenios (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                VARCHAR(36)  NOT NULL,
    paciente_id         BIGINT       NOT NULL,
    convenio_id         BIGINT       NOT NULL,
    numero_carteirinha  VARCHAR(30)  NOT NULL,
    validade            DATE,
    ativo               BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_por          VARCHAR(150),
    atualizado_por      VARCHAR(150),
    data_criacao        TIMESTAMP(6) NOT NULL,
    data_modificacao    TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_pacientes_convenios_uuid UNIQUE (uuid),
    CONSTRAINT fk_pacientes_convenios_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_pacientes_convenios_convenio FOREIGN KEY (convenio_id) REFERENCES convenios (id)
);

CREATE INDEX ix_pacientes_convenios_paciente ON pacientes_convenios (paciente_id);
CREATE INDEX ix_pacientes_convenios_convenio ON pacientes_convenios (convenio_id);
