-- RBAC: o acesso deixa de ser um perfil fixo por usuário e passa a ser por permissões.
-- O usuário recebe as permissões dos seus grupos mais permissões avulsas. As permissões são fixas no código
-- (enum Permissao); grupos e vínculos são dados que o administrador gerencia.

CREATE TABLE grupos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(50)  NOT NULL,
    descricao        VARCHAR(255),
    padrao           BOOLEAN      NOT NULL DEFAULT FALSE,  -- grupo de cargo/médico: não pode ser removido
    data_criacao     TIMESTAMP(6) NOT NULL,
    data_modificacao TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_grupos_nome UNIQUE (nome)
);

CREATE TABLE grupo_permissoes (
    grupo_id  BIGINT      NOT NULL,
    permissao VARCHAR(50) NOT NULL,
    CONSTRAINT pk_grupo_permissoes PRIMARY KEY (grupo_id, permissao),
    CONSTRAINT fk_grupo_permissoes_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id) ON DELETE CASCADE
);

CREATE TABLE usuario_grupos (
    usuario_id BIGINT NOT NULL,
    grupo_id   BIGINT NOT NULL,
    CONSTRAINT pk_usuario_grupos PRIMARY KEY (usuario_id, grupo_id),
    CONSTRAINT fk_usuario_grupos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_grupos_grupo FOREIGN KEY (grupo_id) REFERENCES grupos (id)
);

CREATE TABLE usuario_permissoes (
    usuario_id BIGINT      NOT NULL,
    permissao  VARCHAR(50) NOT NULL,
    CONSTRAINT pk_usuario_permissoes PRIMARY KEY (usuario_id, permissao),
    CONSTRAINT fk_usuario_permissoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX ix_usuario_grupos_grupo ON usuario_grupos (grupo_id);

